#!/usr/bin/env python3
"""Signed WiFi updates for the ESP32 boards (optional).

    python3 tools/ota_sign.py keygen          # once: private key + src/web/ota_pubkey.h
    python3 tools/ota_sign.py sign fw.bin     # fw.bin -> fw.signed.bin (PlatformIO does this by itself)
    python3 tools/ota_sign.py verify fw.signed.bin

The private key stays on your computer: ~/.allquad/ota_private.pem (or the file named by AQ_OTA_KEY). It is
never in the project folder, never committed. Firmware built after "keygen" carries the public key and
then takes over WiFi only images signed with that private key (ECDSA P-256 over SHA-256 of the image).
LOSE THE KEY = no more WiFi updates for those boards: flash over USB (a build without the key, or with a
new key). Back the key file up. Without a key nothing changes (unsigned updates as before).

Signed image = firmware image + 72-byte trailer: "AQSIG1\\0\\0" + r (32 bytes) + s (32 bytes).
"""
import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HDR = os.path.join(ROOT, "src", "web", "ota_pubkey.h")
MAGIC = b"AQSIG1\0\0"
TRAILER = 72


def key_path():
    return os.environ.get("AQ_OTA_KEY") or os.path.join(os.path.expanduser("~"), ".allquad", "ota_private.pem")


def _crypto():
    try:
        from cryptography.hazmat.primitives import hashes, serialization
        from cryptography.hazmat.primitives.asymmetric import ec, utils
        return hashes, serialization, ec, utils
    except ImportError:
        sys.exit("pip install cryptography")


def write_header(pub_bytes):
    body = ", ".join("0x%02x" % b for b in pub_bytes) if pub_bytes else ""
    with open(HDR, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/ota_sign.py keygen. Public key for signed WiFi updates (ECDSA P-256,\n"
                "// uncompressed point). Length 0 = no key: unsigned updates are accepted (default).\n"
                "#pragma once\n#include <stdint.h>\n\n")
        f.write("static const uint8_t OTA_PUBKEY[] = {%s};\n" % (body or "0"))
        f.write("static const unsigned OTA_PUBKEY_LEN = %d;\n" % len(pub_bytes))


def load_key():
    hashes, serialization, ec, utils = _crypto()
    p = key_path()
    if not os.path.exists(p):
        return None
    with open(p, "rb") as f:
        return serialization.load_pem_private_key(f.read(), password=None)


def pub_bytes(key):
    hashes, serialization, ec, utils = _crypto()
    return key.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)


def keygen():
    hashes, serialization, ec, utils = _crypto()
    p = key_path()
    if os.path.exists(p):
        sys.exit("%s exists already (delete it yourself to make a new one: boards with the old key then need USB)" % p)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    k = ec.generate_private_key(ec.SECP256R1())
    with open(p, "wb") as f:
        f.write(k.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
    try:
        os.chmod(p, 0o600)
    except OSError:
        pass
    write_header(pub_bytes(k))
    print("private key: %s  (BACK IT UP, keep it secret)\npublic key:  %s (build and flash once over USB)" % (p, HDR))


def sign_bytes(data, key):
    hashes, serialization, ec, utils = _crypto()
    if data[-TRAILER:-64] == MAGIC:
        data = data[:-TRAILER]  # signed already: sign again
    der = key.sign(data, ec.ECDSA(hashes.SHA256()))
    r, s = utils.decode_dss_signature(der)
    return data + MAGIC + r.to_bytes(32, "big") + s.to_bytes(32, "big")


def verify_bytes(data, pub):
    hashes, serialization, ec, utils = _crypto()
    from cryptography.exceptions import InvalidSignature
    if len(data) < TRAILER or data[-TRAILER:-64] != MAGIC:
        return False
    body, r, s = data[:-TRAILER], int.from_bytes(data[-64:-32], "big"), int.from_bytes(data[-32:], "big")
    k = ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256R1(), pub)
    try:
        k.verify(utils.encode_dss_signature(r, s), body, ec.ECDSA(hashes.SHA256()))
        return True
    except InvalidSignature:
        return False


def main():
    if len(sys.argv) < 2 or sys.argv[1] not in ("keygen", "sign", "verify"):
        sys.exit(__doc__)
    if sys.argv[1] == "keygen":
        return keygen()
    key = load_key()
    if not key:
        sys.exit("no key (%s): run keygen first" % key_path())
    src = sys.argv[2]
    data = open(src, "rb").read()
    if sys.argv[1] == "sign":
        out = sys.argv[3] if len(sys.argv) > 3 else src.replace(".bin", ".signed.bin")
        open(out, "wb").write(sign_bytes(data, key))
        print("signed: %s (sha256 %s)" % (out, hashlib.sha256(data).hexdigest()[:16]))
    else:
        ok = verify_bytes(data, pub_bytes(key))
        print("signature OK" if ok else "NOT signed with this key")
        sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
